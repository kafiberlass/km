/**
 * Где открывать карту, когда человек не дома.
 *
 * Вся геометрия тумана привязана к точке отсчёта — месту первой
 * прогулки, — и карта открывалась там же. Пока человек ходит по своему
 * городу, разницы нет. Но стоит уехать, и приложение показывает пустой
 * двор в тысяче километров: ни себя, ни друга, который рядом.
 *
 * Точку отсчёта при этом трогать нельзя — на ней держится весь туман.
 * Меняется только то, куда смотрит камера в первый момент.
 */

import { haversineMeters, type LngLat } from '@/core/geo/mercator';

/**
 * С какого расстояния считаем, что человек «не дома».
 *
 * Пять километров — заведомо больше обычной прогулки и заведомо меньше
 * поездки в другой город. На таком расстоянии дом всё равно не виден
 * на экране, так что показывать его незачем.
 */
export const AWAY_FROM_HOME_M = 5000;

export function isAwayFromHome(
  origin: LngLat,
  point: LngLat | null,
  thresholdM: number = AWAY_FROM_HOME_M,
): boolean {
  if (!point) return false;
  return haversineMeters(origin, point) > thresholdM;
}
