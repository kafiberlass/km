/**
 * Когда приложение ищет места само.
 *
 * Раньше поиск был только по кнопке на вкладке «Места». Это честно по
 * отношению к чужому бесплатному серверу, но нечестно по отношению
 * к человеку: пока кнопка не найдена и не нажата, на карте стоят три
 * демонстрационных места из Москвы, а в Казани, где человек живёт, —
 * ни кремля, ни мечети, ни набережной.
 *
 * Поэтому один раз, при первом запуске с известной домашней точкой,
 * приложение спрашивает места само. Именно один раз: повторная попытка
 * — только если в прошлый не нашлось ничего (не было связи, сервер был
 * занят), и не чаще раза в сутки. Кнопка остаётся — ею переспрашивают,
 * когда переехали или захотели другой радиус.
 *
 * Здесь только правило «пора или не пора»: сеть в nearby.ts, вызов —
 * в useWalkStore. Так правило можно проверить тестами.
 */

import { SEARCH_RADIUS_M } from './nearby';

/**
 * Два захода. Первый — всё вокруг дома, включая кафе и скверы: это места
 * на вечер. Второй — достопримечательности по всему городу: до кремля
 * из спального района пешком не дойдёшь, но дойти хочется именно туда,
 * а не в кофейню за углом.
 */
export const AUTO_RADII_M: readonly number[] = [SEARCH_RADIUS_M, 25_000];

/** Ключ в kv: когда в последний раз пробовали искать сами. */
export const AUTO_SEARCH_KEY = 'places-auto-search-at';

/** Не нашлось — не долбимся: следующая попытка не раньше, чем через сутки. */
export const RETRY_AFTER_MS = 24 * 60 * 60 * 1000;

export interface AutoSearchState {
  /** Известна ли домашняя точка: без неё искать негде. */
  hasOrigin: boolean;
  /** Сколько достопримечательностей уже лежит в базе. */
  landmarks: number;
  /** Сколько вообще настоящих мест из OSM уже лежит в базе. */
  osmPlaces: number;
  /** Когда пробовали в прошлый раз, ms, или null — если никогда. */
  lastAttemptAt: number | null;
  now: number;
}

export function shouldAutoSearch(state: AutoSearchState): boolean {
  if (!state.hasOrigin) return false;

  // Достопримечательности уже есть — искать нечего.
  //
  // Смотрим именно на них, а не на места вообще: у того, кто нажимал
  // кнопку до того, как приложение научилось находить кремли и мечети,
  // база полна кафе, и по признаку «места есть» он бы так и остался
  // без единой достопримечательности.
  if (state.landmarks > 0) return false;

  if (state.lastAttemptAt == null) return true;
  if (state.now - state.lastAttemptAt < RETRY_AFTER_MS) return false;

  // Сходили, места приехали, а достопримечательностей нет — значит, их
  // нет и в OSM вокруг. Ходить за ними каждые сутки незачем.
  return state.osmPlaces === 0;
}

/**
 * Место из OSM, а не из демонстрационного набора.
 *
 * Признак — идентификатор: у настоящих он вида `osm-way-123`, у демо —
 * `demo-cafe-1`. Отдельной колонки заводить не стали: ради одного
 * признака это миграция схемы у всех, у кого приложение уже стоит.
 */
export function isOsmPlace(id: string): boolean {
  return id.startsWith('osm-');
}
