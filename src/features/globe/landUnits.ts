/**
 * Суша, переведённая в единичные векторы — один раз за запуск.
 *
 * Поворот планеты пересобирает контуры материков целиком: 4700 точек.
 * Синусы и косинусы каждой точки при этом не меняются — меняется только
 * то, каким боком Земля повёрнута к зрителю. Считая их заново на каждый
 * поворот, приложение тратило почти полтора миллисекунды на градус, и
 * вращение шло заметными рывками.
 *
 * Здесь они посчитаны заранее, а в самом повороте остаётся умножение.
 * Плоские массивы, а не массивы объектов: 14 тысяч чисел в куче
 * собираются мусорщиком ровно тогда, когда этого не ждёшь.
 */

import { LAND_RINGS } from './land';
import { unitOf } from './projection';

export const LAND_UNITS: readonly Float64Array[] = LAND_RINGS.map((ring) => {
  const units = new Float64Array((ring.length / 2) * 3);

  for (let i = 0, out = 0; i < ring.length; i += 2, out += 3) {
    const [a, b, c] = unitOf(ring[i]!, ring[i + 1]!);
    units[out] = a;
    units[out + 1] = b;
    units[out + 2] = c;
  }

  return units;
});
