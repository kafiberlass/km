/**
 * Когда копия уезжает на сервер сама.
 *
 * Кнопка «сохранить копию» решает задачу только для того, кто про неё
 * помнит. Телефон теряется не в тот день, когда человек думает о резервных
 * копиях, поэтому копия должна уезжать без него.
 *
 * Два ограничения, из-за которых это не «отправлять всегда»:
 *
 *   Копия — это вся история целиком, а не последняя прогулка. Год ходьбы
 *   весит несколько мегабайт, и отправлять их после каждого выхода
 *   из дома значит тратить чужой мобильный интернет. Отсюда пауза между
 *   отправками.
 *
 *   Отправлять нечего, если ничего не изменилось. Считаем по числу
 *   прогулок: оно растёт ровно тогда, когда появляется что терять.
 *
 * Здесь только решение «пора или нет» — без базы, сети и часов, чтобы
 * это можно было проверить тестами.
 */

/**
 * Сколько ждать между копиями.
 *
 * Полсуток: потерять можно максимум один день ходьбы, а телефон,
 * с которого гуляют дважды в день, не будет отправлять историю дважды.
 */
export const MIN_INTERVAL_MS = 12 * 60 * 60 * 1000;

export interface AutoBackupCheck {
  /** Включена ли автоматическая копия. */
  enabled: boolean;
  /** Собрано ли приложение с ключами сервера. */
  serverReady: boolean;
  /** Когда уехала последняя копия. null — не уезжала ни разу. */
  lastAt: number | null;
  /** Сколько прогулок было в последней копии. */
  lastWalks: number | null;
  /** Сколько прогулок в телефоне сейчас. */
  walks: number;
  now: number;
}

export function shouldAutoBackup(check: AutoBackupCheck): boolean {
  const { enabled, serverReady, lastAt, lastWalks, walks, now } = check;

  if (!enabled || !serverReady) return false;

  // Пустую историю сохранять незачем: на новом телефоне такая копия
  // ещё и затрёт настоящую, если человек нажмёт «восстановить».
  if (walks <= 0) return false;

  // Копии нет вовсе — отправляем, не дожидаясь никаких пауз.
  if (lastAt == null) return true;

  // Ничего нового с прошлого раза.
  if (lastWalks != null && walks <= lastWalks) return false;

  const passed = now - lastAt;

  // Часы съехали назад (перевод времени, смена пояса, сброс настроек):
  // ждать в такой ситуации значит не отправить копию никогда. Новые
  // прогулки уже есть — проверка выше это подтвердила.
  if (passed < 0) return true;

  return passed >= MIN_INTERVAL_MS;
}
