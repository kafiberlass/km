/**
 * Шаги.
 *
 * Считаются из пройденного расстояния, а не читаются с шагомера — и это
 * стоит сказать честно, потому что разница есть.
 *
 * Настоящий шагомер живёт в нативной части телефона (на iPhone это
 * CoreMotion, на Android — датчик шагов), а её нельзя добавить обновлением
 * по воздуху: нужна пересборка и новая установка у всех, у кого приложение
 * уже стоит. Расстояние же приложение и так меряет — по нему шаги
 * восстанавливаются с точностью около десяти процентов, чего для «сколько
 * я сегодня прошёл» достаточно.
 *
 * Поэтому число показывается со знаком «≈» и округляется до десятков:
 * точность, которой нет, не должна изображаться цифрами.
 */

/**
 * Длина шага при спокойной ходьбе, метры.
 *
 * 0,72 — примерно среднее для взрослого человека: у мужчин ближе к 0,78,
 * у женщин к 0,67, у всех — больше при быстрой ходьбе и меньше в толпе
 * или в гору.
 */
export const STRIDE_M = 0.72;

/** Шаги по расстоянию. Округление до десятков — см. заголовок файла. */
export function stepsFromMeters(meters: number, strideM: number = STRIDE_M): number {
  if (!Number.isFinite(meters) || meters <= 0) return 0;
  if (!Number.isFinite(strideM) || strideM <= 0) return 0;

  const steps = meters / strideM;
  // До сотни шагов округление до десятков съело бы весь смысл числа:
  // «10 шагов» и «0 шагов» — разные сообщения.
  return steps < 100 ? Math.round(steps) : Math.round(steps / 10) * 10;
}

/**
 * «12 480» — с неразрывными пробелами по три цифры.
 *
 * Через Intl не идём намеренно: он в разных сборках расставляет разные
 * пробелы, а число в моноширинном шрифте от этого прыгает.
 */
export function formatSteps(steps: number): string {
  const whole = Math.max(0, Math.round(steps));
  const digits = String(whole);

  let out = '';
  for (let i = 0; i < digits.length; i += 1) {
    const fromEnd = digits.length - i;
    if (i > 0 && fromEnd % 3 === 0) out += ' ';
    out += digits[i];
  }
  return out;
}
