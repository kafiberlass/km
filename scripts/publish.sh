#!/usr/bin/env bash
#
# Отправить обновление всем, у кого стоит приложение.
#
#   npm run send
#   npm run send "Добавила места Казани"
#
# Ни кабеля, ни файлов, ни пересборки: новый код уезжает на сервер Expo,
# телефоны забирают его сами при следующем запуске. Работает и на iPhone,
# и на Android, в любом городе.
#
# Чего так отправить нельзя — нативную часть: новые разрешения, новые
# нативные модули, иконку, версию Expo. Их видно по runtimeVersion в
# app.json: пока он совпадает со сборкой на телефоне, обновление приедет,
# а после его смены нужен новый файл приложения. Поэтому скрипт сам
# сверяет, не менялось ли нативное, и предупреждает.

set -euo pipefail

cd "$(dirname "$0")/.."

bold() { printf '\033[1m%s\033[0m\n' "$1"; }
step() { printf '\n\033[1m→ %s\033[0m\n' "$1"; }
warn() { printf '\033[33m%s\033[0m\n' "$1"; }
fail() { printf '\n\033[31m✗ %s\033[0m\n\n' "$1" >&2; exit 1; }

# Ветка обновлений. Совпадает с каналом, которым собираются приложения
# (профиль preview в eas.json): канал — это то, на что подписан телефон,
# ветка — то, куда кладётся код. Разойдутся — обновление уедет в пустоту.
BRANCH="preview"

MESSAGE="${1:-}"
if [ -z "$MESSAGE" ]; then
  # Без подписи обновления в списке на expo.dev неразличимы. Заголовок
  # последнего коммита — ровно то, что и нужно написать.
  MESSAGE="$(git log -1 --pretty=%s 2>/dev/null || echo 'обновление')"
fi

step "Проверяю инструмент"
if ! npx --no-install eas --version >/dev/null 2>&1; then
  bold "  Ставлю eas-cli (один раз, пара минут)"
  npm install --global eas-cli || fail "Не удалось поставить eas-cli.
Попробуйте вручную: npm install --global eas-cli"
fi

step "Проверяю аккаунт Expo"
if ! eas whoami >/dev/null 2>&1; then
  fail "Нужен вход в Expo.

  eas login

Если браузер не открывается или страница не грузится — через токен:
  expo.dev → аватар справа сверху → Account settings → Access tokens
  → Create token, потом здесь:

     export EXPO_TOKEN=вставьте-токен-сюда
     npm run send"
fi
bold "  Вошли как: $(eas whoami 2>/dev/null || echo 'по токену')"

step "Проверяю настройку обновлений"
HAS_URL="$(node -e '
  const app = require("./app.json");
  const updates = (app.expo && app.expo.updates) || {};
  process.stdout.write(updates.url ? "yes" : "no");
')"

if [ "$HAS_URL" = "no" ]; then
  bold "  Настраиваю в первый раз"
  # Дописывает в app.json адрес обновлений и номер проекта — они привязаны
  # к аккаунту, поэтому в репозитории их нет и быть не может.
  eas update:configure --non-interactive \
    || fail "Не удалось настроить обновления. Покажите разработчику вывод выше."

  cat <<'NOTE'

Обновления настроены, но приложениям об этом ещё неизвестно: они собраны
раньше и адреса обновлений не знают. Нужен один — последний — новый файл:

  npm run build:android     (для Android)
  npm run setup:ios:release (для своего iPhone, кабелем)

После этой установки обновления начнут приезжать сами, и файлы больше
никому отправлять не придётся.

NOTE
fi

step "Проверяю, хватит ли обновления по воздуху"
# Нативное меняется редко, но если изменилось — телефоны обновление
# просто не возьмут, и молчание выглядит как «ничего не работает».
LAST_BUILD_MARK="$(git log -1 --pretty=%H -- app.json package.json plugins 2>/dev/null || true)"
HEAD_MARK="$(git rev-parse HEAD 2>/dev/null || true)"
if [ -n "$LAST_BUILD_MARK" ] && [ "$LAST_BUILD_MARK" = "$HEAD_MARK" ]; then
  warn "  В последнем коммите менялись app.json, package.json или plugins."
  warn "  Если там появился новый нативный модуль или разрешение —"
  warn "  обновления по воздуху не хватит, нужна пересборка."
fi

# Обновление собирается здесь, на этой машине, и ключи Supabase попадают
# в него из .env. Если их нет, уедет сборка с демонстрационными друзьями —
# и заменит собой рабочую у всех, кому приложение уже поставили. Это хуже,
# чем не отправить ничего.
step "Проверяю ключи сервера"
MISSING_KEYS=""
for key in EXPO_PUBLIC_SUPABASE_URL EXPO_PUBLIC_SUPABASE_ANON_KEY; do
  if [ ! -f .env ] || ! grep -qE "^${key}=.+" .env; then
    MISSING_KEYS="$MISSING_KEYS $key"
  fi
done

if [ -n "$MISSING_KEYS" ]; then
  fail "В файле .env нет ключей:$MISSING_KEYS

Без них обновление увезёт всем демонстрационных друзей вместо настоящих.
Ключи лежат в личном кабинете Supabase: Project settings -> API,
это адрес проекта и ключ anon (он публичный по замыслу).

Файл .env создаётся в корне проекта, по строке на ключ:
  EXPO_PUBLIC_SUPABASE_URL=https://ваш-проект.supabase.co
  EXPO_PUBLIC_SUPABASE_ANON_KEY=ключ"
fi
bold "  На месте"

step "Отправляю обновление"
bold "  Подпись: $MESSAGE"
eas update --branch "$BRANCH" --environment "$BRANCH" --message "$MESSAGE" \
  || fail "Не удалось отправить обновление. Вывод выше — покажите разработчику."

cat <<'NOTE'

Готово. Что теперь происходит у людей:

  1. Телефон проверяет обновление при каждом запуске приложения — сам.
  2. Находит, тихо скачивает в фоне.
  3. Применяет при следующем открытии.

То есть мама увидит новое, закрыв и снова открыв приложение (иногда со
второго раза — первый уходит на скачивание). Можно и вручную:
Профиль → ОБНОВЛЕНИЕ → ПРОВЕРИТЬ ОБНОВЛЕНИЯ.

NOTE
