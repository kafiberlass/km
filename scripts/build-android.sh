#!/usr/bin/env bash
#
# Сборка приложения для Android одной командой.
#
#   npm run build:android
#
# Собирает не на компьютере, а на серверах Expo, и это осознанно: локальная
# сборка требует Android Studio, JDK и SDK — десяток гигабайт и отдельный
# вечер настройки. В облаке нужен только аккаунт Expo (бесплатный).
#
# На выходе — файл .apk и ссылка на него. Ссылку можно отправить кому угодно:
# на Android приложение ставится прямо из файла, без магазина, и живёт
# сколько угодно — семидневной подписи, как на iPhone, здесь нет.

set -euo pipefail

cd "$(dirname "$0")/.."

# shellcheck source=scripts/lib/sync-env.sh
. "$(dirname "$0")/lib/sync-env.sh"

bold() { printf '\033[1m%s\033[0m\n' "$1"; }
step() { printf '\n\033[1m→ %s\033[0m\n' "$1"; }
warn() { printf '\033[33m%s\033[0m\n' "$1"; }
fail() { printf '\n\033[31m✗ %s\033[0m\n\n' "$1" >&2; exit 1; }

step "Проверяю инструмент сборки"
if ! npx --no-install eas --version >/dev/null 2>&1; then
  bold "  Ставлю eas-cli (один раз, пара минут)"
  npm install --global eas-cli || fail "Не удалось поставить eas-cli.
Попробуйте вручную: npm install --global eas-cli
Если ругается на права — sudo npm install --global eas-cli"
fi

step "Проверяю аккаунт Expo"
if ! eas whoami >/dev/null 2>&1; then
  bold "  Нужен вход. Аккаунт бесплатный: если его нет, заведите на expo.dev"

  # Вход через браузер работает не везде: страница подтверждения
  # возвращается на localhost, и если до неё не доходит (VPN, блокировки,
  # другой браузер по умолчанию), человек видит «не удаётся получить
  # доступ к сайту» и упирается в тупик. Поэтому на этот случай есть
  # второй путь — токен, который вставляется прямо в терминал.
  eas login || fail "Войти через браузер не получилось.

Второй способ, без браузера:
  1. Откройте expo.dev → нажмите на свой аватар справа сверху
     → Account settings → Access tokens → Create token.
  2. Скопируйте токен (он показывается один раз).
  3. Выполните здесь, подставив свой токен:

     export EXPO_TOKEN=вставьте-токен-сюда
     npm run build:android

Токен живёт только в этом окне терминала: закроете — придётся выполнить
строку export заново."
fi

if [ -n "${EXPO_TOKEN:-}" ]; then
  bold "  Вход по токену"
else
  bold "  Вошли как: $(eas whoami 2>/dev/null)"
fi

step "Передаю ключи Supabase в облако сборки"
sync_env_to_expo preview

# Без этого собранное приложение не знает, куда ходить за обновлениями,
# и останется навсегда таким, каким собрано: новый код придётся снова
# присылать файлом. Адрес привязан к аккаунту, поэтому в репозитории его
# нет — eas дописывает его в app.json здесь, на машине владельца.
step "Проверяю настройку обновлений по воздуху"
HAS_URL="$(node -e '
  const app = require("./app.json");
  const updates = (app.expo && app.expo.updates) || {};
  process.stdout.write(updates.url ? "yes" : "no");
')"
if [ "$HAS_URL" = "yes" ]; then
  bold "  Уже настроены"
else
  bold "  Настраиваю (один раз)"
  eas update:configure --non-interactive \
    || warn "  Не получилось. Приложение соберётся, но обновляться по воздуху не будет."
fi

step "Собираю (10–20 минут, можно закрыть терминал)"
bold "  Прогресс и ссылка на готовый файл — на expo.dev, в разделе Builds."
eas build --platform android --profile preview

cat <<'NOTE'

Готово. Что дальше:

  1. Скачайте .apk по ссылке выше (или на expo.dev → Builds).
  2. Отправьте файл тому, кому ставим: почтой, мессенджером, как угодно.
  3. На Android-телефоне открыть файл и разрешить установку
     из этого источника, когда система спросит.

Файл отправляется один раз. Дальше обновления уезжают по воздуху:

  npm run send

Собирать заново нужно только тогда, когда меняется нативная часть —
об этом скажет и npm run update, и сам npm run send.

Android, в отличие от iPhone, ничего не отзывает: приложение работает,
пока его не удалят.

NOTE
